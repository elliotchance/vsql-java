// GenerateUnsupported writes src/main/java/io/github/elliotchance/vsql/Unsupported*.java:
// an abstract class for each JDBC interface that the driver implements, with
// every abstract method of the interface throwing SQLFeatureNotSupportedException.
// The driver's classes extend them and override the methods they support.
// UnsupportedPreparedStatement extends VsqlStatement (which has the Statement
// methods), so it only has the methods that PreparedStatement adds.
//
//   java scripts/GenerateUnsupported.java

import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.Parameter;
import java.lang.reflect.Type;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Collectors;

public class GenerateUnsupported {
    public static void main(String[] args) throws Exception {
        for (Class<?> c : List.of(
                java.sql.Connection.class,
                java.sql.Statement.class,
                java.sql.PreparedStatement.class,
                java.sql.ResultSet.class,
                java.sql.ResultSetMetaData.class,
                java.sql.DatabaseMetaData.class)) {
            generate(c);
        }
    }

    static void generate(Class<?> iface) throws Exception {
        String name = "Unsupported" + iface.getSimpleName();
        StringBuilder b = new StringBuilder();
        b.append("// Code generated by scripts/GenerateUnsupported.java. DO NOT EDIT.\n\n");
        b.append("package io.github.elliotchance.vsql;\n\n");
        b.append("/** Every method of {@link ").append(iface.getName())
                .append("} throws {@link java.sql.SQLFeatureNotSupportedException}. */\n");
        b.append("@SuppressWarnings({\"deprecation\", \"removal\"})\n");
        boolean prepared = iface == java.sql.PreparedStatement.class;
        b.append("abstract class ").append(name);
        if (prepared) {
            b.append(" extends VsqlStatement");
        }
        b.append(" implements ").append(iface.getName()).append(" {\n");
        if (prepared) {
            b.append("\n    ").append(name)
                    .append("(VsqlConnection connection) {\n        super(connection);\n    }\n");
        }

        Method[] all = prepared ? iface.getDeclaredMethods() : iface.getMethods();
        List<Method> methods = Arrays.stream(all)
                .filter(m -> Modifier.isAbstract(m.getModifiers()))
                .filter(m -> !m.getName().equals("unwrap") && !m.getName().equals("isWrapperFor")
                        && !(m.getName().equals("close") && m.getParameterCount() == 0))
                .sorted(Comparator.comparing(Method::getName).thenComparing(Method::toGenericString))
                .collect(Collectors.toList());
        for (Method m : methods) {
            b.append("\n");
            if (m.isAnnotationPresent(Deprecated.class)) {
                b.append("    @Deprecated\n");
            }
            b.append("    @Override\n    public ");
            if (m.getTypeParameters().length > 0) {
                b.append("<").append(Arrays.stream(m.getTypeParameters()).map(Type::getTypeName)
                        .collect(Collectors.joining(", "))).append("> ");
            }
            b.append(typeName(m.getGenericReturnType())).append(" ").append(m.getName()).append("(");
            Parameter[] ps = m.getParameters();
            Type[] ts = m.getGenericParameterTypes();
            for (int i = 0; i < ps.length; i++) {
                if (i > 0) {
                    b.append(", ");
                }
                b.append(typeName(ts[i])).append(" p").append(i);
            }
            b.append(")");
            Class<?>[] exceptions = m.getExceptionTypes();
            if (exceptions.length > 0) {
                b.append(" throws ").append(Arrays.stream(exceptions).map(Class::getName)
                        .collect(Collectors.joining(", ")));
            }
            String what = iface.getSimpleName() + "." + m.getName();
            if (Arrays.asList(exceptions).contains(java.sql.SQLException.class)) {
                b.append(" {\n        throw Errors.unsupported(\"").append(what).append("\");\n    }\n");
            } else {
                // A method that can't throw an SQLException.
                b.append(" {\n        throw new UnsupportedOperationException(\"vsql: ").append(what)
                        .append(" is not supported\");\n    }\n");
            }
        }
        b.append("}\n");
        Files.writeString(Path.of("src/main/java/io/github/elliotchance/vsql/" + name + ".java"), b);
        System.out.println(name + ": " + methods.size() + " methods");
    }

    static String typeName(Type t) {
        return t.getTypeName().replace('$', '.');
    }
}
